#!/usr/bin/env node
/**
 * storm-check-label-2026-11-17.js — one-off, idempotent label sweep (Jo approved
 * 2026-11-17). The free tool at /storm-check is "Storm Damage Check"; the old
 * labels "Is It Worth a Claim?" and "Storm Damage Claim Check" implied the tool
 * predicts claim outcomes. Sources (site-src/partials, add-roofscore-freetools-nav.js)
 * are fixed by hand; this script handles the hand-authored pages and llms.txt.
 * Only the label token changes, never the surrounding prose. EOLs are preserved
 * (plain string split/join, no regex over line breaks). docs/llms-full.txt is
 * regenerated by scripts/build-llms.mjs and is not touched here.
 *
 * Usage: node scripts/storm-check-label-2026-11-17.js [--check]
 * After a real run: node scripts/apply-partials.js, then
 *   node scripts/stamp-page-dates.mjs --write --date=2026-11-17 <changed pages>
 */
'use strict';
const fs = require('fs');
const path = require('path');

const DOCS = path.join(__dirname, '..', 'docs');
const CHECK = process.argv.includes('--check');
const NEW = 'Storm Damage Check';

// [old, new] — exact, case-sensitive, applied in order.
const SWAPS = [
  ['Storm Damage Claim Check — Is It Worth Filing?', NEW],
  ['Storm Damage Claim Check', NEW],
  ['Is It Worth a Claim?', NEW],
  ['Is It Worth a Claim tool', NEW + ' tool'],
  ['link1_name="Is it worth a claim?"', 'link1_name="' + NEW + '"'],
  ['<a href="/storm-check">Is it worth a claim?</a>', '<a href="/storm-check">' + NEW + '</a>'],
  ['storm claim check', 'storm damage check'],
];

function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(html|txt)$/.test(e.name) && e.name !== 'llms-full.txt') out.push(p);
  }
  return out;
}

const changed = [];
for (const f of walk(DOCS, [])) {
  const src = fs.readFileSync(f, 'utf8');
  let out = src;
  for (const [a, b] of SWAPS) out = out.split(a).join(b);
  if (out !== src) {
    changed.push(path.relative(DOCS, f).split(path.sep).join('/'));
    if (!CHECK) fs.writeFileSync(f, out);
  }
}
if (CHECK) {
  if (changed.length) {
    console.error('storm-check label: ' + changed.length + ' file(s) still need the sweep:\n  ' + changed.join('\n  '));
    process.exit(1);
  }
  console.log('storm-check label: clean');
} else {
  console.log(changed.length + ' file(s) changed');
  console.log(changed.join('\n'));
}
