// ── TOWNFAQ ───────────────────────────────────────────────────────────
// An answer is built from segments; `opt` segments are dropped (last first)
// until the answer fits 80 words, `pad` segments are added until it reaches
// 40. The visible answer keeps links; the JSON-LD copy is plain text.
function answer(t, segs, q) {
  const text = (list) => list.map((s) => s.text).join(' ');
  let list = segs.filter((s) => !s.pad);
  while (words(text(list)) > 80) {
    const i = list.map((s) => !!s.opt).lastIndexOf(true);
    if (i < 0) fail(`${t.slug}: FAQ answer over 80 words with nothing optional left — "${q}"`);
    list.splice(i, 1);
  }
  for (const p of segs.filter((s) => s.pad)) { if (words(text(list)) >= 40) break; if (words(text(list).concat(' ', p.text)) <= 80) list.push(p); }
  const n = words(text(list));
  if (n < 40 || n > 80) fail(`${t.slug}: FAQ answer is ${n} words (want 40-80) — "${q}"`);
  const html = list.map((s) => {
    const h = esc(s.text);
    if (!s.href) return h;
    if (!h.includes(esc(s.anchor))) fail(`${t.slug}: link anchor "${s.anchor}" not in its sentence`);
    return h.replace(esc(s.anchor), link(s.href, esc(s.anchor)));
  }).join(' ');
  return { q, a: text(list), html };
}
const seg = (text, extra = {}) => ({ text, ...extra });

function faqPermit(t) {
  const T = t.town, p = t.permit;
  const q = pick(t, 'q1', [`Do I need a permit to replace my roof in ${T}?`, `Does a roof replacement in ${T} need a permit?`, `Is a permit required to re-roof a house in ${T}?`]);
  const first = { yes: 'Yes.', no: 'Not for the roof covering itself.', unknown: 'No official page settles it.', varies: 'It depends on the job.' }[p.status];
  const segs = [seg(first), seg(p.status === 'unknown' ? p.summary.replace(/^I have not found a written (answer|rule)[.] /, '') : p.summary)];
  if (p.ask) segs.push(seg(`Ask ${p.ask} before work starts.`));
  if (t.historic && t.historic.review) segs.push(seg('Historic districts have their own review; see below.', { opt: true }));
  segs.push(seg(`Source: ${p.authority}.`, { href: p.url, anchor: p.authority, opt: true }));
  segs.push(seg('Rules change, so confirm for your address before the tear-off.', { pad: true }));
  segs.push(seg('Either way, the free inspection and written estimate come first.', { pad: true }));
  return answer(t, segs, q);
}

function faqHail(t) {
  const T = t.town, s = t.storms, r = radiusMi(t);
  if (s.hailReports) {
    const big = s.maxHail, last = s.lastHail;
    const count = `NOAA logged ${s.hailReports} report${s.hailReports === 1 ? '' : 's'} of hail an inch or larger within about ${r} miles of ${T} from 2019 through June 2026, on ${s.hailDays === 1 ? 'one day' : s.hailDays + ' days'}.`;
    const bigSeg = seg(`The largest measured ${inches(big.in)}${HAIL[big.in] ? ` (${HAIL[big.in]} size)` : ''}, on ${fdate(big.date)} near ${big.place}.`, { href: noaaUrl(big.noaa), anchor: fdate(big.date) });
    const v = hash(t.slug + '|q2') % 3;
    let q, segs;
    if (v === 1) {
      q = `When did hail last hit near ${T}?`;
      segs = [seg(`The most recent report was ${hailIn(last.in)} hail on ${fdate(last.date)} near ${last.place}.`, { href: noaaUrl(last.noaa), anchor: fdate(last.date) }), seg(count)];
      if (big.noaa !== last.noaa) segs.push({ ...bigSeg, opt: true });
    } else {
      q = v === 0 ? `Has ${T} had big hail recently?` : `Has there been large hail near ${T}?`;
      segs = [seg(`Yes. ${count}`), bigSeg];
    }
    segs.push(seg(pick(t, 'q2o', ['A report near town doesn’t mean your roof was hit; that takes someone on the roof.', 'Whether your roof took any of it is a separate question, and only an inspection answers it.', 'Storm cells are narrow, so a report down the road says nothing certain about your street.']), { opt: true }));
    segs.push(seg('Hail that size can bruise shingles without leaving anything you’d see from the yard.', { pad: true }));
    return answer(t, segs, q);
  }
  const q = pick(t, 'q2', [`Has ${T} had hail recently?`, `Does ${T} get much hail?`]);
  const strongest = [...s.events].sort((a, b) => score(b) - score(a))[0];
  const what = s.tornadoes ? 'wind and tornadoes' : 'wind';
  const segs = [
    seg(`Not on the record. NOAA shows no hail an inch or larger within about ${r} miles of ${T} between January 2019 and June 2026.`),
    strongest ? seg(`What it does show is ${what}; the strongest entry is the ${describe(t, strongest).replace(/; NOAA.*$/, '')} on ${fdate(strongest.date)}.`, { href: noaaUrl(strongest.noaa), anchor: fdate(strongest.date) }) : seg(`What it does show is ${what}.`),
    seg('Spotter reports miss things, so a quiet record isn’t a guarantee for your roof.', { opt: true }),
    seg('Wind lifts shingle edges and ridge caps, which is where I look first.', { pad: true }),
  ];
  return answer(t, segs, q);
}

