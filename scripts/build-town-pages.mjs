// ── small helpers ─────────────────────────────────────────────────────
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
function hash(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
const pick = (t, key, arr) => arr[hash(t.slug + '|' + key) % arr.length];
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const fdate = (iso) => { const [y, m, d] = iso.split('-').map(Number); return `${MONTHS[m - 1]} ${d}, ${y}`; };
const mi = (km) => { const v = km * 0.621371; return v < 1 ? v.toFixed(1) : String(Math.round(v * 10) / 10); };
const radiusMi = (t) => String(Math.round(t.storms.radiusKm * 0.621371 * 2) / 2);
const mph = (kt) => Math.round(kt * 1.15078);
const noaaUrl = (id) => `https://www.ncdc.noaa.gov/stormevents/eventdetails.jsp?id=${id}`;
const HAIL = { 1: 'quarter', 1.25: 'half-dollar', 1.5: 'ping-pong-ball', 1.75: 'golf-ball', 2: 'hen-egg', 2.5: 'tennis-ball', 2.75: 'baseball', 3: 'teacup' };
const hailIn = (x) => (x === 1 ? '1-inch' : `${x}-inch`);
const inches = (x) => (x === 1 ? '1 inch' : `${x} inches`);
const hailSize = (x) => (HAIL[x] ? `${hailIn(x)} (${HAIL[x]}-size)` : hailIn(x));
const money = (usd) => (usd >= 1e6 ? `$${(usd / 1e6).toFixed(1)} million` : `$${Math.round(usd / 1000)},000`);
const words = (s) => s.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
const link = (href, text) => `<a href="${esc(href)}" target="_blank" rel="noopener">${text}</a>`;
const where = (t, e) => e.place + (e.county ? ` (${e.county} Co.)` : '');
const ageOf = (t) => 2026 - t.housing.medianYearBuilt;
const bucket = (y) => (y < 1946 ? 'prewar' : y < 1960 ? 'postwar' : y < 1980 ? 'midcentury' : y < 1996 ? 'eighties' : 'newer');
const score = (e) => (e.kind === 'tornado' ? 200 + Number(e.rating.slice(2)) * 20 : e.kind === 'hail' ? e.hailIn * 60 : e.kt);

function fail(msg) { console.error(`build-town-pages: ${msg}`); process.exit(1); }

// ── storm wording ─────────────────────────────────────────────────────
function describe(t, e) {
  const at = where(t, e);
  let s;
  if (e.kind === 'tornado') {
    const [a, b] = e.place.split(' to ');
    s = b ? `${e.rating} tornado, ${e.pathMi}-mile path from ${a} to ${b}${e.county ? ` (${e.county} Co.)` : ''}` : `${e.rating} tornado near ${at}, ${e.pathMi}-mile path`;
  } else if (e.kind === 'hail') {
    s = `${hailSize(e.hailIn)} hail at ${at}`;
  } else if (e.basis === 'measured') {
    s = `${e.kt}-knot (${mph(e.kt)} mph) gust measured at ${at}`;
  } else {
    const [a, b] = e.place.split(' to ');
    const loc = b ? `between ${a} and ${b}${e.county ? ` (${e.county} Co.)` : ''}` : `near ${at}`;
    s = e.basis === 'estimated' ? `estimated ${mph(e.kt)} mph wind gust ${loc}` : `wind damage report ${loc}`;
  }
  if (e.damageUsd) s += `; NOAA damage estimate ${money(e.damageUsd)}`;
  return s;
}
const isThin = (t) => !t.storms.events.some((e) => e.kind !== 'wind' || e.kt >= 60);

// Biggest event anywhere in the town's county, from every town's list — used
// when a town's own record holds nothing but routine wind-damage reports.
function countyHeadline(t) {
  const county = t.county.split(' / ')[0].replace(/ County$/, '');
  let best = null, bestTown = null;
  for (const o of TOWNS) {
    for (const e of o.storms.events) {
      const c = e.county || o.county.split(' / ')[0].replace(/ County$/, '');
      if (c !== county || o.slug === t.slug) continue;
      const k = (x) => score(x) + (x.damageUsd || 0) / 1e9;
      if (!best || k(e) > k(best)) { best = e; bestTown = o; }
    }
  }
  return best && score(best) >= 60 ? { e: best, o: bestTown, county } : null;
}

