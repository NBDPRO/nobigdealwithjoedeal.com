// Card phrasings are assigned, not hashed: walking the towns in slug order,
// each takes the unused combination farthest (fewest shared cards) from every
// combination already taken, so no two area pages carry the same set and
// most pairs share at most two of the four cards.
const WHY_COMBO = (() => {
  let combos = [[]];
  for (const v of WHY) combos = combos.flatMap((c) => v.map((_, i) => [...c, i]));
  const shared = (a, b) => a.filter((x, i) => x === b[i]).length;
  const used = [], out = new Map();
  for (const slug of TOWNS.map((t) => t.slug).sort()) {
    let best = null, bestKey = -1;
    for (const c of combos) {
      if (used.some((u) => shared(u, c) === c.length)) continue;
      const worst = used.length ? Math.max(...used.map((u) => shared(u, c))) : 0;
      const key = (WHY.length - worst) * 1e6 + (hash(slug + '|' + c.join('')) % 1e6);
      if (key > bestKey) { bestKey = key; best = c; }
    }
    used.push(best); out.set(slug, best);
  }
  return out;
})();
function townWhy(t) {
  const combo = WHY_COMBO.get(t.slug);
  const cards = WHY.map((variants, i) => {
    const [h, p] = variants[combo[i]];
    return `      <div class="why-card">
        <h3>${h}</h3>
        <p>${p}</p>
      </div>`;
  }).join('\n');
  return `    <div class="why-grid">
${cards}
    </div>`;
}

