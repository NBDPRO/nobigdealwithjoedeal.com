// ── stamping ──────────────────────────────────────────────────────────
const toEol = (s, eol) => (eol === '\n' ? s : s.replace(/\n/g, eol));
function stampRegion(src, name, body, eol, rel) {
  const start = `<!-- ${name}:START -->`, end = `<!-- ${name}:END -->`;
  const a = src.indexOf(start), b = src.indexOf(end);
  if (a < 0 || b < a) fail(`${rel}: missing ${start} … ${end} markers (place them once by hand; see the header of this script)`);
  if (src.indexOf(start, a + 1) >= 0) fail(`${rel}: ${start} appears twice`);
  return src.slice(0, a) + toEol(`${start}\n${STAMP}\n${body}\n`, eol) + src.slice(b);
}
const stale = [];
let written = 0;
function stampFile(file, regions) {
  const rel = path.relative(ROOT, file).replace(/\\/g, '/');
  const src = readFileSync(file, 'utf8');
  const eol = src.includes('\r\n') ? '\r\n' : '\n';
  let out = src;
  for (const [name, body] of regions) out = stampRegion(out, name, body, eol, rel);
  if (/\r(?!\n)/.test(out)) fail(`${rel}: stamped output would contain a lone CR byte`);
  if (out === src) return;
  if (CHECK) { stale.push(rel); return; }
  writeFileSync(file, out);
  written++;
}

