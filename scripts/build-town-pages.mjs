#!/usr/bin/env node
/**
 * build-town-pages.mjs — stamps the town-specific, data-backed regions on the
 * /areas/<town> pages (and a short "In <Town>" note on three sets of
 * town-specific service pages) from ONE source: site-src/data/towns.json.
 *
 * WHY (2026-09-27): the 43 area pages were near-duplicates of each other
 * (5-gram Jaccard of the main text, town names masked: mean 0.41, worst pair
 * 0.73) — the doorway-page pattern. Each page now carries facts that are true
 * of that town only, every one with a source link: the Census median build
 * year, the NOAA storm record near town, who issues the re-roof permit and
 * what their page says, historic-district review, and a few local facts.
 * Sentence frames are chosen per town from several phrasings (deterministic
 * hash of the slug), so the generated copy is not itself a template clone.
 *
 * REGIONS (generator-owned — never hand-edit between the markers):
 *   docs/areas/<slug>.html
 *     <!-- TOWNWHY:START -->   … the four "why NBD" cards (varied phrasings)
 *     <!-- TOWNFACTS:START --> … housing age, storm list, permits, local facts
 *     <!-- TOWNFAQ:START -->   … 4-5 visible town Q&As + their FAQPage JSON-LD
 *   docs/services/{roof-inspection,siding-replacement,siding-repair}-<slug>.html
 *     <!-- TOWNLOCAL:START --> … a 2-3 sentence "In <Town>" paragraph
 *   Each region ends at the matching <!-- NAME:END -->. The markers are placed
 *   once by hand (see the vault note); this script only restamps between
 *   them, and fails if an area page or a town is missing its markers or data.
 *
 * EOL: pages are CRLF in a Windows worktree and LF on CI. Blocks are rendered
 * in LF and converted ONCE to the destination file's ending (same discipline
 * as build-projects.mjs), and every write is checked for lone CR bytes.
 *
 * Usage:
 *   node scripts/build-town-pages.mjs           # restamp
 *   node scripts/build-town-pages.mjs --check   # write nothing; exit 1 on drift
 *
 * To update the facts: edit site-src/data/towns.json, run this script, commit
 * the data file and the pages together. How the data was compiled and how to
 * refresh it: documentation/audit/TOWN-PAGES-LOCAL-DATA-2026-09-27.md.
 */
