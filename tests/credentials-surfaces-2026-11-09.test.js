/**
 * tests/credentials-surfaces-2026-11-09.test.js - the credential claims that
 * live OUTSIDE scripts/build-credentials.mjs's own surfaces must agree with
 * docs/assets/data/credentials.json (the source of truth; only status
 * "active" rows may be claimed anywhere).
 *
 * WHY (plan: CONTENT-PHOTOS-CREDENTIALS-PLAN-2026-11-09, "Fix now"):
 *   A. functions/agent-mcp-logic.js told the AI assistant NBD holds "IKO
 *      ROOFPRO Advantage" while credentials.json holds IKO as pending and not
 *      public (IKO bars public representation of that tier). The assistant
 *      drafts customer copy, so it must never state a credential the site
 *      hides.
 *   B. docs/llms.txt carried a hand-written credentials line that disagreed
 *      with the data file (TAMKO "certified July 8, 2026" vs since 2026-07,
 *      American Operator missing). It is now the LLMS:CREDENTIALS region,
 *      generated by scripts/build-llms.mjs (--check-regions is the CI gate;
 *      tests/build-llms-modes.test.js proves a data edit turns it red).
 *   C. The footer cert-bar disclaimer (site-src/partials/footer-*.html,
 *      stamped onto every page by scripts/apply-partials.js) named GAF and
 *      TAMKO only, while /credentials' independence line names James Hardie
 *      too. The two must name the same issuers, and every active
 *      manufacturer row must be named. (A trademark clause is only owed for a
 *      mark the footer shows: Hardie's is not shown, so it gets none.)
 *
 * Pure Node, no deps. Run: node tests/credentials-surfaces-2026-11-09.test.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');

let passed = 0, failed = 0;
function ok(label, cond, detail) {
  if (cond) { console.log('  ✓ ' + label); passed++; }
  else { console.log('  ✗ ' + label + (detail ? ' - ' + detail : '')); failed++; }
}

const rows = JSON.parse(read('docs/assets/data/credentials.json')).credentials;
const active = rows.filter((r) => r.status === 'active').sort((a, b) => a.order - b.order);
const held = rows.filter((r) => r.status !== 'active');
const short = (r) => r.issuerShort || r.issuer;
const ofType = (t) => active.filter((r) => r.type === t);

console.log('A. the AI assistant\'s credential list matches the active rows');
{
  const L = require(path.join(ROOT, 'functions', 'agent-mcp-logic.js'));
  const cred = L.rulesReference().credentials;
  const certs = cred.certifications || [];
  const mems = cred.memberships || [];
  const mfr = ofType('manufacturer');
  const mem = ofType('membership');

  ok('one certification per active manufacturer row', certs.length === mfr.length,
    certs.length + ' listed vs ' + mfr.length + ' active: ' + JSON.stringify(certs));
  mfr.forEach((r, i) => {
    ok('certification ' + (i + 1) + ' is ' + r.id + ' (issuer' + (r.contractorId ? ' + ID ' + r.contractorId : '') + ')',
      !!certs[i] && certs[i].includes(short(r)) && (!r.contractorId || certs[i].includes(r.contractorId)), certs[i]);
  });
  ok('one membership per active membership row', mems.length === mem.length,
    mems.length + ' listed vs ' + mem.length + ' active: ' + JSON.stringify(mems));
  mem.forEach((r, i) => {
    ok('membership ' + (i + 1) + ' is ' + r.id, !!mems[i] && mems[i].includes(short(r)), mems[i]);
  });
  ofType('insurance').forEach((r) => {
    ok('the note carries the insurance wording "' + r.claimWording + '"', String(cred.note || '').includes(r.claimWording));
  });
  const listed = certs.concat(mems).join(' | ');
  held.forEach((r) => {
    ok('a ' + r.status + ' row (' + r.id + ') is never listed', !listed.includes(short(r)), listed);
  });
  // Belt and braces: a known roofing/siding issuer with no active row.
  const ISSUERS = ['GAF', 'TAMKO', 'IKO', 'Owens Corning', 'CertainTeed', 'Atlas', 'Malarkey', 'James Hardie', 'LP SmartSide', 'American Operator', 'BBB', 'Haag'];
  const activeNames = active.map(short).join(' | ');
  const stray = ISSUERS.filter((n) => new RegExp('\\b' + n + '\\b').test(listed) && !activeNames.includes(n));
  ok('no issuer is listed that has no active row', stray.length === 0, stray.join(', '));
  ok('no honesty word in the list (Master Elite only as "not Master Elite"; never Licensed)',
    !/master\s*elite/i.test(listed.replace(/not Master Elite/g, '')) && !/\blicensed\b/i.test(listed), listed);
}

console.log('B. docs/llms.txt credentials come from the generated region');
{
  const llms = read('docs/llms.txt');
  const S = '<!-- LLMS:CREDENTIALS:START -->', E = '<!-- LLMS:CREDENTIALS:END -->';
  const a = llms.indexOf(S), b = llms.indexOf(E);
  ok('exactly one LLMS:CREDENTIALS marker pair, in order',
    a !== -1 && b > a && llms.indexOf(S, a + 1) === -1 && llms.indexOf(E, b + 1) === -1);
  const region = a !== -1 && b > a ? llms.slice(a, b) : '';
  const outside = a !== -1 && b > a ? llms.slice(0, a) + llms.slice(b) : llms;
  active.forEach((r) => {
    const want = [r.name, r.summary].concat(r.contractorId ? [r.contractorId] : [], r.verifyUrl ? [r.verifyUrl] : []);
    const miss = want.filter((w) => !region.includes(w));
    ok('the region states ' + r.id + ' (name, summary, ID, verify link)', miss.length === 0, 'missing: ' + miss.join(' | '));
  });
  held.forEach((r) => ok('the region never names the ' + r.status + ' row ' + r.id, !region.includes(short(r))));
  ok('no honesty word in the region', !/master\s*elite|\blicensed\b|president['\u2019]?s\s*club/i.test(region));
  ok('outside the region, no hand-kept credential ID or certified-on date (they drift)',
    !active.some((r) => r.contractorId && outside.includes(r.contractorId)) && !/certified (January|February|March|April|May|June|July|August|September|October|November|December)/i.test(outside),
    (outside.match(/.{0,60}(181382|1162011|certified (July|August)).{0,40}/) || [])[0]);
  ok('the region links /credentials', region.includes('https://nobigdealwithjoedeal.com/credentials'));
  // 2026-11-09 review: the heading must not promise a verify link for every row
  // while some active rows (insurance, James Hardie) have no verifyUrl.
  ok('the region heading promises a verify link only if every active row has one',
    active.every((r) => r.verifyUrl) || !/with its verify link/i.test(region));
}

console.log('C. the footer disclaimer and /credentials name the same issuers');
{
  const credPage = read('docs/credentials.html');
  const fine = (/<div class="cred-fine">\s*<p>([\s\S]*?)<\/p>/.exec(credPage) || [])[1] || '';
  ok('/credentials has its independence line', /not an employee or agent of/i.test(fine), fine.slice(0, 120));
  const names = [...new Set(active.filter((r) => r.type !== 'insurance').map(short))];
  const named = (text) => names.filter((n) => text.includes(n)).join(', ');
  for (const r of ofType('manufacturer')) {
    ok('/credentials names manufacturer ' + short(r), fine.includes(short(r)));
  }
  const partials = fs.readdirSync(path.join(ROOT, 'site-src', 'partials')).filter((f) => /^footer-.*\.html$/.test(f));
  let seen = 0;
  for (const f of partials) {
    const html = read('site-src/partials/' + f);
    if (!html.includes('data-nbd-certbar')) continue;
    seen++;
    const disc = (/<span data-nosnippet>(Independent Contractor\.[\s\S]*?)<\/span>/.exec(html) || [])[1] || '';
    // The independence sentences end where the trademark clauses begin.
    const indep = disc.split(/GAF® and GAF Certified™/)[0];
    ok(f + ': the disclaimer is present', !!indep);
    ok(f + ': independence names the same issuers as /credentials (' + named(fine) + ')',
      named(indep) === named(fine), 'footer: ' + named(indep));
  }
  ok('the footer partials carrying the cert bar were checked', seen >= 4, String(seen));

  // 2026-11-09 review: 13 pages carry the footer by hand (no partial), so the
  // partial check above cannot see them. Every shipped page's cert-bar
  // disclaimer (the site-wide independence statement) must name the same
  // issuers as /credentials. Page-specific lines (a product page's copyright
  // line naming the marks it shows, a blog post's "either manufacturer") are
  // not the site-wide list and are left to their pages.
  const htmlFiles = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'pro' && e.name !== 'node_modules') walk(p); }
      else if (e.name.endsWith('.html')) htmlFiles.push(p);
    }
  })(path.join(ROOT, 'docs'));
  let pages = 0;
  const stale = [];
  for (const p of htmlFiles) {
    const html = fs.readFileSync(p, 'utf8');
    if (!html.includes('data-nbd-certbar')) continue;
    pages++;
    const bar = html.slice(html.indexOf('data-nbd-certbar'));
    const m = /<span data-nosnippet>Independent Contractor\. Not an employee or agent of ([^.]*)\./.exec(bar);
    if (!m) stale.push(path.relative(ROOT, p) + ': no cert-bar disclaimer');
    else if (named(m[1]) !== named(fine)) stale.push(path.relative(ROOT, p) + ': "' + m[1].trim() + '"');
  }
  ok('every page with the cert bar was scanned (partial-stamped and hand-carried footers)', pages >= 280, String(pages));
  ok('every cert-bar disclaimer on those pages names the same issuers as /credentials (' + named(fine) + ')',
    stale.length === 0, stale.slice(0, 5).join(' || ') + (stale.length > 5 ? ' (+' + (stale.length - 5) + ' more)' : ''));
}

console.log('\n' + passed + ' passed, ' + failed + ' failed');
process.exit(failed ? 1 : 0);
